/** ISR según la tarifa acumulada del mes (art. 106 LISR). Lanza si no hay tarifa cargada para ese año. */
export function isrTarifa(base: number, anio: number, mes: number): number {
  const tabla = TARIFA_106[anio]?.[mes]
  if (!tabla) throw new Error(`No hay tarifa de ISR cargada para ${mes}/${anio}. Agrégala desde el Anexo 8 de la RMF de ese año.`)
  if (base <= 0) return 0
  const r = tabla.find(([inf, sup]) => base >= inf && (sup === null || base <= sup + 0.0099)) || tabla[tabla.length - 1]
  return Math.round((r[2] + (base - r[0]) * (r[3] / 100)) * 100) / 100
}
